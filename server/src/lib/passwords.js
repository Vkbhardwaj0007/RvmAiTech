/**
 * Password hashing and policy.
 *
 * Argon2id is the primary algorithm. bcrypt hashes written by the previous
 * version of this app are still accepted on login and transparently upgraded
 * to Argon2id at that moment, so nobody has to reset their password.
 */
const argon2 = require('argon2');
const bcrypt = require('bcryptjs');
const { config } = require('../config/env');

/* ------------------------------------------------------------------ hashing */

function argon2Options() {
  return {
    type: argon2.argon2id,
    memoryCost: config.argon2.memoryCost,
    timeCost: config.argon2.timeCost,
    parallelism: config.argon2.parallelism,
  };
}

/** Argon2id hash. The salt is generated by the library, per hash. */
async function hashPassword(plain) {
  return argon2.hash(String(plain), argon2Options());
}

function isArgon2Hash(hash) {
  return typeof hash === 'string' && hash.startsWith('$argon2');
}

function isBcryptHash(hash) {
  return typeof hash === 'string' && /^\$2[aby]?\$/.test(hash);
}

/**
 * Verifies `plain` against a stored hash of either algorithm.
 *
 * Returns { ok, needsRehash }. `needsRehash` is true when the password was
 * correct but the stored hash is a legacy bcrypt one (or Argon2 parameters
 * have since been raised), which is the caller's cue to re-store it.
 *
 * Never throws on a malformed hash — a corrupt record is an authentication
 * failure, not a 500.
 */
async function verifyPassword(plain, hash) {
  const candidate = String(plain ?? '');

  if (isArgon2Hash(hash)) {
    try {
      const ok = await argon2.verify(hash, candidate);
      return { ok, needsRehash: ok && argon2.needsRehash(hash, argon2Options()) };
    } catch {
      return { ok: false, needsRehash: false };
    }
  }

  if (isBcryptHash(hash)) {
    try {
      const ok = await bcrypt.compare(candidate, hash);
      return { ok, needsRehash: ok };
    } catch {
      return { ok: false, needsRehash: false };
    }
  }

  return { ok: false, needsRehash: false };
}

/**
 * Burns roughly the same CPU as a real verification, for the
 * account-does-not-exist path. Without this, "unknown user" answers much
 * faster than "wrong password" and the timing alone enumerates accounts.
 *
 * The digest is deliberately discarded.
 */
const DUMMY_HASH_PLAIN = 'timing-equalisation-placeholder';
let dummyHashPromise = null;

async function dummyVerify() {
  if (!dummyHashPromise) dummyHashPromise = hashPassword(DUMMY_HASH_PLAIN);
  try {
    const h = await dummyHashPromise;
    await argon2.verify(h, 'not-the-password');
  } catch {
    /* expected: the comparison fails. We only want the work. */
  }
  return { ok: false, needsRehash: false };
}

/* ------------------------------------------------------------------- policy */

// Screened out regardless of length. Short list on purpose: it catches the
// passwords people actually pick when told "12 characters", without pretending
// to be a breach corpus. Point PASSWORD_DENYLIST_FILE at a real list (e.g. the
// SecLists top-100k) for production-grade screening.
const COMMON_PASSWORDS = new Set([
  'password', 'password1', 'password12', 'password123', 'password1234',
  'passw0rd123', 'qwertyuiop', 'qwerty123456', '123456789012', '1234567890',
  'adminadmin', 'administrator', 'admin@123', 'admin@1234', 'admin@12345',
  'letmein123', 'welcome123', 'welcome1234', 'iloveyou123', 'changeme123',
  'rvmaitech', 'rvmaitech123', 'rvmaitech@123',
]);

let extraDenylist = null;
function denylist() {
  if (extraDenylist) return extraDenylist;
  extraDenylist = new Set(COMMON_PASSWORDS);
  const file = process.env.PASSWORD_DENYLIST_FILE;
  if (file) {
    try {
      const lines = require('fs').readFileSync(file, 'utf8').split(/\r?\n/);
      for (const line of lines) {
        const v = line.trim().toLowerCase();
        if (v) extraDenylist.add(v);
      }
    } catch {
      /* a missing denylist file must not stop the app booting */
    }
  }
  return extraDenylist;
}

/**
 * Validates a candidate password against the policy.
 *
 * `context` holds values the password must not simply echo (user id, name,
 * email), because "rvmaitech-admin" is a bad password however long it is.
 *
 * Returns an array of human-readable problems; empty means acceptable.
 */
function passwordProblems(plain, context = {}) {
  const problems = [];
  const value = String(plain ?? '');
  const { minLength, maxLength } = config.password;

  if (value.length < minLength) problems.push(`Password must be at least ${minLength} characters`);
  // Argon2 has no bcrypt-style 72-byte truncation, but an unbounded password is
  // an easy CPU-exhaustion lever, so we still cap it.
  if (value.length > maxLength) problems.push(`Password must be at most ${maxLength} characters`);
  if (value.trim().length === 0 && value.length > 0) problems.push('Password cannot be only whitespace');

  const lower = value.toLowerCase();
  if (denylist().has(lower)) problems.push('That password is too common — pick something less guessable');

  // A single repeated character, or a straight run, whatever the length.
  if (value.length >= minLength && /^(.)\1+$/.test(value)) {
    problems.push('Password cannot be a single repeated character');
  }

  for (const [label, raw] of Object.entries(context)) {
    const hint = String(raw ?? '').toLowerCase().trim();
    // Only meaningful fragments: a 2-character name would match everything.
    if (hint.length >= 4 && lower.includes(hint)) {
      problems.push(`Password must not contain your ${label}`);
    }
  }

  return problems;
}

module.exports = {
  hashPassword,
  verifyPassword,
  dummyVerify,
  passwordProblems,
  isArgon2Hash,
  isBcryptHash,
};
